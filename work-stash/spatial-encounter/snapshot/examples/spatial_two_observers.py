"""EXPERIMENTAL: two observers sample a StatisticalGroup at separate boundaries.

Run with ``python examples/spatial_two_observers.py``. The local Cartesian
coordinates use the existing group sensor's metre-named range contract, not a
geographic datum. Group composition is established once at boundary 1; the
boundary-2 observation uses that committed objective Reality.
"""
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'src'))

from group_observation import ObserveGroupAction
from spatial import ISEAGrid
from spatial_group_observation import _build_scenario


def _schedule_second_observation(world, encounter, observer, group, ledger):
    # This declared keyed stream succeeds with roll 11 for this observer,
    # target, start time and seed. Evidence remains generated by native code.
    action = ObserveGroupAction(world, observer.id, group.id, 1,
        seed=4, random_key='second-observer',
        observation={'coarse_range_m': 1000, 'detailed_range_m': 450},
        interpretation={'skill_name': 'spot', 'expert_level': 5},
        ledger=ledger)
    choice = encounter.schedule_choice((action,))
    return action, choice


def demo_data():
    (world, encounter, first_observer, second_observer, group,
     first_ledger, second_ledger, first_action, first_choice, rng,
     first_inspection) = _build_scenario()
    first_records = tuple(group._composition_reality._records.items())
    first_revision = group._composition_reality.revision
    first_count = group.materialized_count
    first_evidence = first_ledger.evidence[0]
    first_beliefs = first_ledger.belief_history

    second_action, second_choice = _schedule_second_observation(
        world, encounter, second_observer, group, second_ledger)
    encounter.step(1)
    inspection = encounter.inspect_committed()

    truth = {key: group.counts()[key]
             for key in ('humans', 'livestock', 'dogs')}
    ledgers = ((first_observer, first_ledger, first_action, first_choice),
               (second_observer, second_ledger, second_action, second_choice))
    observations = {}
    for label, (observer, ledger, action, choice) in zip(('first', 'second'), ledgers):
        evidence = ledger.evidence[0]
        interpretation = ledger.interpretation_for(action.id)
        record = inspection.action(action.id)
        practice = inspection.target(observer.id).practice_history[-1]
        observations[label] = {
            'observer_id': observer.id,
            'action_id': action.id,
            'choice_id': choice.id,
            'target_id': record.facts.target_ids[0],
            'boundary': record.resolved_boundary,
            'outcome': record.facts.outcome,
            'evidence_id': evidence.id,
            'evidence_observer_id': evidence.observer_id,
            'evidence_group_id': evidence.group_id,
            'evidence_time': evidence.time,
            'estimates': {key: evidence.reports[key].estimate for key in truth},
            'interpretation_estimates': {key: interpretation.reports[key].estimate
                                         for key in truth},
            'belief_revisions': tuple((row.category, row.estimate,
                                       row.trigger_observation_id)
                                      for row in ledger.belief_history),
            'practice_time': practice.time,
            'practice_experience': practice.experience,
            'practice_action_id': practice.exercises[0].action_id,
            'practice_effect_identity': str(practice.exercises[0].effect_identity),
            'action_effect_ids': tuple(str(row.identity) for row in record.effects),
        }

    after_records = tuple(group._composition_reality._records.items())
    facts = inspection.objective[group.id].facts
    grid = ISEAGrid(radius=1.0)
    return {
        'encounter': {'id': encounter.id, 'time': encounter.time,
                      'committed_boundaries': tuple(row.boundary
                          for row in encounter.__dict__['_atomic_interval_history'])},
        'objective_group': {
            'group_id': group.id,
            'composition': truth,
            'ledger_revision_after_first': first_revision,
            'ledger_revision_after_second': group._composition_reality.revision,
            'formation_fact_revisions': tuple(sorted({fact.revision
                                                       for fact in facts.values()})),
            'second_request_reuses_established_facts': all(
                fact.established_before for fact in facts.values()),
            'fact_storage_unchanged_after_second': (
                len(first_records) == len(after_records)
                and all(k1 is k2 and v1 is v2 for (k1, v1), (k2, v2)
                        in zip(first_records, after_records))),
            'materialized_beings': first_count,
        },
        'observers': observations,
        'observer_independence': {
            'different_evidence_ids': first_evidence.id != second_ledger.evidence[0].id,
            'first_evidence_preserved': first_ledger.evidence[0] is first_evidence,
            'first_beliefs_preserved': all(a is b for a, b in
                zip(first_ledger.belief_history, first_beliefs)),
            'second_has_only_its_observation': tuple(second_ledger._evidence) ==
                (second_action.id,),
        },
        'positions': {
            'first_observer': first_observer.get_position().as_tuple(),
            'second_observer': second_observer.get_position().as_tuple(),
            'group': group.get_position().as_tuple(),
        },
        'derived_isea_cells': {
            'first_observer': str(first_observer.spatial_cell(grid, 5)),
            'second_observer': str(second_observer.spatial_cell(grid, 5)),
            'group': str(group.spatial_cell(grid, 5)),
        },
        'first_boundary_remains_committed': first_inspection.boundary == 1,
        'rng_state_version': rng.state[0],
    }


if __name__ == '__main__':
    print(json.dumps(demo_data(), indent=2, sort_keys=True))
