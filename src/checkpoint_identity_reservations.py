"""Inactive identity reservation plans for the bounded imported Run history.

These detached plans describe identities which a future trusted-local restore
must reserve.  This module never attaches a plan to a native Encounter or
ChoiceBook and never changes any identity allocator.
"""
from dataclasses import dataclass
import hashlib
import json

from frozen_practice import ImportedPracticeRejected, freeze_imported_run_practice


class IdentityReservationRejected(ValueError):
    """The bounded historical identity set is inconsistent or unsupported."""


@dataclass(frozen=True)
class HistoricalIdentityReservationPlan:
    schema: str
    universe_id: str
    encounter_id: str
    historical_choice_ids: tuple
    historical_action_ids: tuple
    event_namespace_ids: tuple
    target_object_ids: tuple
    causal_effect_ids: tuple
    choice_book_counter_floor: int
    minimum_next_draft_suffix: int
    source_counter_exact: bool
    source_counter_note: str
    content_digest: str


@dataclass(frozen=True)
class FutureIdentityCheck:
    schema: str
    choice_id: str
    action_ids: tuple
    accepted: bool


def _canonical_choice_suffix(encounter_id, choice_id):
    """Return the source-generated draft suffix, rejecting other ID forms."""
    prefix = encounter_id + '/draft/'
    if type(choice_id) is not str or not choice_id.startswith(prefix):
        raise IdentityReservationRejected(
            'historical Choice ID is not generated by this Encounter ChoiceBook')
    suffix = choice_id[len(prefix):]
    if (not suffix or not suffix.isascii() or not suffix.isdecimal()
            or suffix.startswith('0')):
        raise IdentityReservationRejected(
            'ChoiceBook draft suffix must be a canonical positive decimal')
    value = int(suffix)
    if value < 1:
        raise IdentityReservationRejected('ChoiceBook draft suffix must be positive')
    return value


def _plan_data(plan):
    return (plan.schema, plan.universe_id, plan.encounter_id,
            plan.historical_choice_ids, plan.historical_action_ids,
            plan.event_namespace_ids, plan.target_object_ids,
            plan.causal_effect_ids, plan.choice_book_counter_floor,
            plan.minimum_next_draft_suffix, plan.source_counter_exact,
            plan.source_counter_note)


def _digest(data):
    return hashlib.sha256(json.dumps(data, ensure_ascii=True,
        separators=(',', ':')).encode('ascii')).hexdigest()


def _valid_effect_identity(value):
    return (type(value) is tuple and len(value) == 6
            and value[0] == 'effect-id'
            and type(value[1]) is str and type(value[2]) is int
            and type(value[3]) is str and type(value[4]) is str
            and type(value[5]) is int)


def plan_historical_identity_reservations(sidecar):
    """Build a pure plan from the exact validated one-boundary Run sidecar."""
    try:
        # Reuse the closed 5E1J2/5E1J3 validator. It rejects extra histories,
        # malformed membership, non-native Action/Target references and any
        # sidecar/projection/practice disagreement.
        prefix = freeze_imported_run_practice(sidecar)
        projection = sidecar.projection
        encounter_id = projection.encounter_id
        if type(encounter_id) is not str or not encounter_id:
            raise IdentityReservationRejected('Encounter identity is missing')
        choice_id = sidecar.choice_id
        suffix = _canonical_choice_suffix(encounter_id, choice_id)
        choice_rows = projection.committed_choices
        if (type(choice_rows) is not tuple or len(choice_rows) != 1
                or choice_rows[0][0] != choice_id
                or choice_rows[0][3] != prefix.action_ids):
            raise IdentityReservationRejected(
                'historical Choice membership does not match the one Run Action')

        action_ids = prefix.action_ids
        root_event_ids = ('0', encounter_id)
        if (len(set(action_ids)) != 1 or any(type(value) is not str or not value
                for value in action_ids) or set(action_ids).intersection(root_event_ids)):
            raise IdentityReservationRejected(
                'historical Action IDs are duplicate, invalid, or collide with root Events')

        target_ids = tuple(sidecar.target_identity_ids)
        if (len(target_ids) != 2 or len(set(target_ids)) != 2
                or any(type(value) is not str or not value for value in target_ids)):
            raise IdentityReservationRejected('historical Target Object identities are invalid')
        effect_ids = tuple(row.identity for row in projection.effects)
        if (not effect_ids or any(not _valid_effect_identity(row) for row in effect_ids)
                or len(set(effect_ids)) != len(effect_ids)):
            raise IdentityReservationRejected('historical causal effect identities are invalid')

        provisional = HistoricalIdentityReservationPlan(
            'universe.historical-run-identity-reservation-plan/1',
            prefix.universe_id, encounter_id, (choice_id,), action_ids,
            root_event_ids + action_ids, target_ids, effect_ids,
            suffix, suffix + 1, False,
            'The historical Choice proves a minimum counter floor; prior draft/validation allocations are not persisted.',
            '')
        return HistoricalIdentityReservationPlan(*(
            tuple(_plan_data(provisional)) + (_digest(_plan_data(provisional)),)))
    except IdentityReservationRejected:
        raise
    except (ImportedPracticeRejected, AttributeError, IndexError, KeyError,
            TypeError, ValueError) as exc:
        raise IdentityReservationRejected(
            'historical identity source is malformed or outside the closed Run subset') from exc


def _validate_plan(plan):
    if (type(plan) is not HistoricalIdentityReservationPlan
            or plan.schema != 'universe.historical-run-identity-reservation-plan/1'
            or plan.source_counter_exact is not False
            or type(plan.choice_book_counter_floor) is not int
            or type(plan.minimum_next_draft_suffix) is not int
            or plan.minimum_next_draft_suffix != plan.choice_book_counter_floor + 1
            or type(plan.historical_choice_ids) is not tuple
            or len(plan.historical_choice_ids) != 1
            or type(plan.historical_action_ids) is not tuple
            or len(plan.historical_action_ids) != 1
            or type(plan.event_namespace_ids) is not tuple
            or type(plan.target_object_ids) is not tuple
            or type(plan.causal_effect_ids) is not tuple
            or type(plan.content_digest) is not str
            or plan.content_digest != _digest(_plan_data(plan))):
        raise IdentityReservationRejected('invalid or edited historical identity plan')
    suffix = _canonical_choice_suffix(plan.encounter_id, plan.historical_choice_ids[0])
    if suffix != plan.choice_book_counter_floor:
        raise IdentityReservationRejected('ChoiceBook counter floor disagrees with historical ID')
    if (type(plan.universe_id) is not str or not plan.universe_id
            or type(plan.encounter_id) is not str or not plan.encounter_id
            or any(type(value) is not str or not value
                   for value in plan.historical_action_ids)
            or len(set(plan.historical_action_ids)) != 1
            or plan.event_namespace_ids != ('0', plan.encounter_id,
                                             *plan.historical_action_ids)
            or any(type(value) is not str or not value for value in plan.target_object_ids)
            or len(set(plan.target_object_ids)) != len(plan.target_object_ids)
            or any(not _valid_effect_identity(value) for value in plan.causal_effect_ids)
            or len(set(plan.causal_effect_ids)) != len(plan.causal_effect_ids)):
        raise IdentityReservationRejected('historical identity namespaces or references are invalid')
    if set(plan.historical_action_ids).intersection(('0', plan.encounter_id)):
        raise IdentityReservationRejected('historical Action IDs collide with root Event IDs')


def validate_future_identity_ids(plan, choice_id, action_ids, *,
                                 existing_event_ids=(), existing_choice_ids=()):
    """Purely check a proposed future Choice and its Action Event identities."""
    _validate_plan(plan)
    if type(action_ids) not in (tuple, list) or not action_ids:
        raise IdentityReservationRejected('future Action IDs must be a non-empty tuple/list')
    actions = tuple(action_ids)
    if any(type(value) is not str or not value for value in actions):
        raise IdentityReservationRejected('future Action IDs must be non-empty strings')
    if len(set(actions)) != len(actions):
        raise IdentityReservationRejected('future Action IDs must be unique')
    if type(existing_event_ids) not in (tuple, list, set, frozenset):
        raise IdentityReservationRejected('existing Event IDs must be a closed collection')
    if type(existing_choice_ids) not in (tuple, list, set, frozenset):
        raise IdentityReservationRejected('existing Choice IDs must be a closed collection')
    if (any(type(value) is not str or not value for value in existing_event_ids)
            or any(type(value) is not str or not value for value in existing_choice_ids)):
        raise IdentityReservationRejected('existing native IDs must be non-empty strings')
    try:
        suffix = _canonical_choice_suffix(plan.encounter_id, choice_id)
    except IdentityReservationRejected:
        raise IdentityReservationRejected('future Choice ID must use the native draft ID form')
    if suffix <= plan.choice_book_counter_floor:
        raise IdentityReservationRejected(
            'future draft suffix must exceed the historical ChoiceBook counter floor')
    if choice_id in plan.historical_choice_ids or choice_id in existing_choice_ids:
        raise IdentityReservationRejected('future Choice ID collides with an existing Choice')
    event_ids = set(plan.event_namespace_ids) | set(existing_event_ids)
    if event_ids.intersection(actions):
        raise IdentityReservationRejected('future Action ID collides in the Event namespace')
    return FutureIdentityCheck('universe.future-identity-check/1', choice_id, actions, True)


def _initialize_quarantined_choice_counter_floor(book, plan):
    """Initialize only a fresh quarantined native ChoiceBook for restore prep.

    This private helper deliberately does not reserve/register a Choice. It
    acquires the book lock and requires all native scheduler stores to be empty.
    """
    from action_choice import ChoiceBook
    from transactional_progression import is_quarantined
    _validate_plan(plan)
    if type(book) is not ChoiceBook or not is_quarantined(book.encounter):
        raise IdentityReservationRejected('counter floor requires a quarantined native ChoiceBook')
    encounter = book.encounter
    world = encounter.universe
    with book.lock:
        if (encounter.id != plan.encounter_id or book.lock is not world._schedule_lock
                or world._choice_books != [book] or book._counter != 0
                or book._drafts or book._closed_drafts or book._tokens or book._choices
                or book._reservations or book._registered or book._states
                or world._schedule_revision != 0):
            raise IdentityReservationRejected('ChoiceBook is not the fresh empty restore-preparation instance')
        if (encounter.time != 1 or encounter.last_processed_boundary != 1
                or encounter.pending_action_list or encounter.finished_action_list
                or encounter.cancelled_action_list):
            raise IdentityReservationRejected('counter initialization requires the closed boundary-1 fixture')
        if any(value in world.event_history for value in plan.historical_action_ids):
            raise IdentityReservationRejected('historical Action ID is already present in Event registry')
        book._counter = plan.choice_book_counter_floor
        return book._counter
